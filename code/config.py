# 目标变量变换：径流呈强右偏（偏度 ~5.0，最大 13700 而均值仅 611），
# 且 NSE 被少数几次特大洪水的平方误差主导（2.8% 的天数贡献 62% 的离差平方和）。
# 对径流取对数后再建模是水文预报的标准做法：
#   (1) 压缩极值的杠杆作用，使损失函数更关注整体过程而非单场洪水；
#   (2) 保证预测值恒为正（exp 回变换）；
#   (3) 误差近似服从对数正态分布，更符合统计假设。
# 评价仍在原始径流尺度上进行，保证与水文指标可比。
